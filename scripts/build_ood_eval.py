"""Build a sliced out-of-distribution (OOD) evaluation set of verification pairs.

The detector is trained and validated mostly on in-distribution Enron pairs, so
the headline AUC hides where it actually fails. This script assembles ONE JSONL
file of verification pairs, each tagged with a ``slice`` naming the OOD axis it
probes, so scripts/eval_ood.py can report metrics per slice and expose the weak
spots (short emails, unseen impersonator LLMs, register shifts, new domains).

Each output line:
    {"pair": ["<text_a>", "<text_b>"], "same": true|false, "slice": "<axis:bucket>"}

Axes built from on-disk assets (no network):

  len:short | len:medium | len:long
      Same/different-author pairs where BOTH emails fall in one length bucket.
      `len:short` is the headline failure mode (results/error_analysis.txt): the
      model scores short different-author pairs as SAME and short same-author
      pairs as DIFFERENT. Buckets by measured word count.

  lenmix:short_long
      Same/different-author pairs where one email is short and one is long — the
      cross-length invariance test (a short note vs a long email by the same
      person should still read as same-author).

  register:cross | register:same
      Same/different-author pairs that cross registers (formal vs casual) vs stay
      within one register. The dominant false-negative mode is same-author pairs
      that cross register/topic.

  gen:<backend>:<model>
      IMPERSONATION / held-out-generator OOD. Positives are two real emails by
      one sender; negatives pair that sender's real email against a synthetic
      ``__syn`` impostor email claiming to be them, generated by that model
      (the ``generator`` column). Train without a given generator's negatives,
      then this slice measures detection of an UNSEEN impostor model.
      The real side is looked up across all splits, so this works with either:
        - train-split synthetics (default) → SEEN senders; isolates the
          impersonator-model axis on known identities.
        - test-split synthetics (generate with --from-split test) → UNSEEN
          senders; true unseen-sender impersonation OOD.
      Provenance is read from the synthetic set's source_split column.

Domain OOD is handled separately: prepare a non-Enron corpus into the same
processed Arrow format (or any ``{pair, same}`` JSONL) and pass it to
eval_ood.py via --extra-pairs name=path.jsonl; those pairs are tagged
``domain:<name>``. See README / data/README.md for corpus suggestions
(PAN, Blog Authorship, Reddit).

Usage:
    python scripts/build_ood_eval.py --config configs/experiments/v9_episodic_shortmail.yaml \\
        --output data/ood/enron_ood_pairs.jsonl
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from collections import defaultdict
from pathlib import Path

_PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(_PROJECT_ROOT / "src"))

from email_fraud.config import load_config
from email_fraud.data.register import detect_register

# Length buckets measured on the email itself (whitespace word count). Looser
# than the generation-time target buckets — here we bucket REAL emails for eval.
_SHORT_MAX = 20
_LONG_MIN = 80


def _len_bucket(text: str) -> str:
    n = len(text.split())
    if n <= _SHORT_MAX:
        return "short"
    if n >= _LONG_MIN:
        return "long"
    return "medium"


def _load_split(processed_dir: str, split: str) -> dict[str, list[str]]:
    """sender_id → list[text] for one split of the processed Arrow dataset."""
    from datasets import load_from_disk

    ds = load_from_disk(processed_dir)[split]
    by_sender: dict[str, list[str]] = defaultdict(list)
    for text, sid in zip(ds["text"], ds["sender_id"]):
        by_sender[sid].append(text)
    return by_sender


def _load_all_splits(processed_dir: str) -> dict[str, list[str]]:
    """sender_id → list[text] merged across every split.

    Splits are sender-disjoint, so merging is unambiguous. Used for the real
    side of impersonation pairs: it finds a source sender's real emails wherever
    they live, so generator slices work whether synthetics were generated from
    the train split or (for unseen-sender eval) the test split.
    """
    from datasets import load_from_disk

    dd = load_from_disk(processed_dir)
    by_sender: dict[str, list[str]] = defaultdict(list)
    for split in dd:
        for text, sid in zip(dd[split]["text"], dd[split]["sender_id"]):
            by_sender[sid].append(text)
    return by_sender


def _sample_same(
    by_sender: dict[str, list[str]],
    n: int,
    rng: random.Random,
    predicate=None,
    max_tries: int = 20000,
) -> list[tuple[str, str]]:
    """n same-author pairs (two distinct texts from one sender) passing predicate.

    predicate(t1, t2) -> bool filters pairs (e.g. both short, or cross-register).
    """
    eligible = [s for s, t in by_sender.items() if len(t) >= 2]
    out: list[tuple[str, str]] = []
    tries = 0
    while len(out) < n and tries < max_tries:
        tries += 1
        s = rng.choice(eligible)
        t1, t2 = rng.sample(by_sender[s], 2)
        if predicate is None or predicate(t1, t2):
            out.append((t1, t2))
    return out


def _sample_diff(
    by_sender: dict[str, list[str]],
    n: int,
    rng: random.Random,
    predicate=None,
    max_tries: int = 20000,
) -> list[tuple[str, str]]:
    """n different-author pairs passing predicate."""
    senders = list(by_sender.keys())
    out: list[tuple[str, str]] = []
    tries = 0
    while len(out) < n and tries < max_tries:
        tries += 1
        s1, s2 = rng.sample(senders, 2)
        t1 = rng.choice(by_sender[s1])
        t2 = rng.choice(by_sender[s2])
        if predicate is None or predicate(t1, t2):
            out.append((t1, t2))
    return out


def _emit(records, pairs, same, slice_name):
    for a, b in pairs:
        records.append({"pair": [a, b], "same": same, "slice": slice_name})


def _build_length_slices(records, by_sender, n_each, rng):
    # Within-bucket pairs: both emails in the same length bucket.
    for bucket in ("short", "medium", "long"):
        pred = lambda t1, t2, b=bucket: _len_bucket(t1) == b and _len_bucket(t2) == b
        same = _sample_same(by_sender, n_each, rng, pred)
        diff = _sample_diff(by_sender, n_each, rng, pred)
        _emit(records, same, True, f"len:{bucket}")
        _emit(records, diff, False, f"len:{bucket}")
    # Cross-length: one short, one long (order-insensitive).
    mix = lambda t1, t2: {_len_bucket(t1), _len_bucket(t2)} == {"short", "long"}
    _emit(records, _sample_same(by_sender, n_each, rng, mix), True, "lenmix:short_long")
    _emit(records, _sample_diff(by_sender, n_each, rng, mix), False, "lenmix:short_long")


def _build_register_slices(records, by_sender, n_each, rng):
    cross = lambda t1, t2: (
        {detect_register(t1), detect_register(t2)} == {"formal", "casual"}
    )
    same_reg = lambda t1, t2: (
        detect_register(t1) == detect_register(t2)
        and detect_register(t1) in ("formal", "casual")
    )
    _emit(records, _sample_same(by_sender, n_each, rng, cross), True, "register:cross")
    _emit(records, _sample_diff(by_sender, n_each, rng, cross), False, "register:cross")
    _emit(records, _sample_same(by_sender, n_each, rng, same_reg), True, "register:same")
    _emit(records, _sample_diff(by_sender, n_each, rng, same_reg), False, "register:same")


def _report_synthetic_provenance(synthetic_path: str) -> None:
    """Print which split(s) the synthetic impostors were generated from."""
    from datasets import load_from_disk

    syn = load_from_disk(synthetic_path)
    if "source_split" not in syn.column_names:
        print("[gen] synthetic set has no source_split column (older generator); "
              "assuming train-sender synthetics (SEEN identities).")
        return
    splits = sorted(set(syn["source_split"]))
    unseen = [s for s in splits if s != "train"]
    tag = (f"UNSEEN-SENDER impersonation eval (source_split={splits})"
           if unseen else "train-sender synthetics (SEEN identities)")
    print(f"[gen] impostor provenance: {tag}")


def _build_generator_slices(records, real_by_sender, synthetic_path, n_each, rng):
    """Impersonation slices, one per generator (the `generator` column).

    Positives: two real emails of a source sender. Negatives: a real email of
    that sender vs a synthetic __syn impostor of the SAME source sender produced
    by this generator.
    """
    from datasets import load_from_disk

    syn = load_from_disk(synthetic_path)
    cols = syn.column_names
    if "source_sender_id" not in cols or "generator" not in cols:
        print(f"[gen] synthetic set missing source_sender_id/generator columns "
              f"({cols}); skipping generator slices.")
        return
    # (generator, source_sender) -> list of impostor texts
    impostor: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for text, src, gen in zip(syn["text"], syn["source_sender_id"], syn["generator"]):
        impostor[gen][src].append(text)

    for gen, by_src in sorted(impostor.items()):
        usable_src = [s for s in by_src if s in real_by_sender and len(real_by_sender[s]) >= 2]
        if not usable_src:
            print(f"[gen] {gen}: no source senders with >=2 real emails; skipping.")
            continue
        # Negatives: real(sender) vs impostor(sender, gen).
        neg: list[tuple[str, str]] = []
        tries = 0
        while len(neg) < n_each and tries < 20000:
            tries += 1
            s = rng.choice(usable_src)
            real_t = rng.choice(real_by_sender[s])
            imp_t = rng.choice(by_src[s])
            neg.append((real_t, imp_t))
        # Positives: two real emails from the same usable source senders.
        pos_pool = {s: real_by_sender[s] for s in usable_src}
        pos = _sample_same(pos_pool, n_each, rng)
        _emit(records, pos, True, f"gen:{gen}")
        _emit(records, neg, False, f"gen:{gen}")


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Build a sliced OOD evaluation pair-set.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    p.add_argument("--config", required=True,
                   help="Config whose data.processed_dir + data.augmentation.synthetic_path "
                        "are used as defaults for the eval sources.")
    p.add_argument("--processed-dir", default=None,
                   help="Override processed Arrow dir (default: config's data.processed_dir).")
    p.add_argument("--synthetic-path", default=None,
                   help="Override synthetic Arrow dir for generator/impersonation slices "
                        "(default: config's data.augmentation.synthetic_path).")
    p.add_argument("--split", default="test", choices=["train", "validation", "test"],
                   help="Split for length/register slices (default: test). Generator slices "
                        "always use the TRAIN split for the real side, since synthetics are "
                        "generated from train senders.")
    p.add_argument("--n-per-slice", type=int, default=300,
                   help="Same pairs (and equally many different pairs) per slice (default: 300).")
    p.add_argument("--output", required=True, help="Output JSONL path.")
    p.add_argument("--seed", type=int, default=123)
    p.add_argument("--no-generator-slices", action="store_true",
                   help="Skip the impersonation/generator slices (length+register only).")
    return p.parse_args()


def main() -> None:
    args = parse_args()
    cfg = load_config(args.config)
    processed_dir = args.processed_dir or cfg.data.processed_dir
    synthetic_path = args.synthetic_path or cfg.data.augmentation.synthetic_path
    rng = random.Random(args.seed)
    n = args.n_per_slice

    print(f"Loading split '{args.split}' from {processed_dir}")
    by_sender = _load_split(processed_dir, args.split)
    print(f"  {len(by_sender)} senders, "
          f"{sum(len(v) for v in by_sender.values())} emails")

    records: list[dict] = []
    _build_length_slices(records, by_sender, n, rng)
    _build_register_slices(records, by_sender, n, rng)

    if not args.no_generator_slices and synthetic_path:
        # Real side of impersonation pairs is looked up across ALL splits, so the
        # slices work whether synthetics were generated from train senders or
        # (--from-split test) from unseen test senders.
        real_all = _load_all_splits(processed_dir)
        _report_synthetic_provenance(synthetic_path)
        _build_generator_slices(records, real_all, synthetic_path, n, rng)
    elif not synthetic_path:
        print("[gen] no synthetic_path configured; skipping generator slices.")

    rng.shuffle(records)
    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    with out.open("w") as fh:
        for rec in records:
            fh.write(json.dumps(rec) + "\n")

    # Composition report.
    by_slice: dict[str, list[int]] = defaultdict(list)
    for r in records:
        by_slice[r["slice"]].append(int(r["same"]))
    print(f"\nWrote {len(records)} pairs across {len(by_slice)} slices → {out}")
    print(f"  {'slice':<32} {'pairs':>7} {'same':>6} {'diff':>6}")
    for sl in sorted(by_slice):
        labels = by_slice[sl]
        print(f"  {sl:<32} {len(labels):>7} {sum(labels):>6} {len(labels) - sum(labels):>6}")


if __name__ == "__main__":
    main()
